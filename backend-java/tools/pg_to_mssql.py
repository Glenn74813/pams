#!/usr/bin/env python3
"""Generates the SQL Server baseline migration from the live PostgreSQL schema.

Run against a PostgreSQL database that Flyway has fully migrated; writes the SQL Server
baseline used by fresh SQL Server installs. Types are mapped (text/json -> nvarchar(max),
boolean -> bit, timestamp(p) -> datetime2(p), serial -> IDENTITY), unique constraints on
nullable columns become filtered unique indexes (SQL Server allows one NULL per unique
constraint), and every foreign key is created without a referential action: SQL Server
refuses most of this schema's cascades as "multiple cascade paths", so ON DELETE CASCADE /
SET NULL are reproduced by INSTEAD OF DELETE triggers, children first, as PostgreSQL does.

usage: PGPASSWORD=... pg_to_mssql.py <host> <user> <db> <out.sql> [seed-table ...]
"""
import json, re, subprocess, sys

host, user, db, out = sys.argv[1:5]
seed_tables = sys.argv[5:]


def q(sql):
    r = subprocess.run(['psql', '-h', host, '-U', user, '-d', db, '-At', '-F', '\x1f', '-c', sql], capture_output=True, text=True, check=True)
    return [line.split('\x1f') for line in r.stdout.splitlines() if line]


# Dropped by V18 on PostgreSQL; never created on SQL Server.
SKIP = {'flyway_schema_history', 'migrations', 'disposal_notifications', 'electronic_signatures', 'procurement_milestones'}
tables = [r[0] for r in q("select table_name from information_schema.tables where table_schema='public' and table_type='BASE TABLE' order by 1") if r[0] not in SKIP]

cols = {}
for t, c, typ, ln, prec, scale, dtp, nullable, default in q("""
        select table_name, column_name, data_type, coalesce(character_maximum_length::text,''), coalesce(numeric_precision::text,''),
               coalesce(numeric_scale::text,''), coalesce(datetime_precision::text,''), is_nullable, coalesce(column_default,'')
        from information_schema.columns where table_schema='public' order by table_name, ordinal_position"""):
    cols.setdefault(t, []).append(dict(name=c, type=typ, len=ln, prec=prec, scale=scale, dtp=dtp, null=nullable == 'YES', default=default))


def ident(n):
    return '[' + n + ']'


def mstype(c):
    t = c['type']
    if t == 'bigint': return 'bigint'
    if t == 'integer': return 'int'
    if t == 'smallint': return 'smallint'
    if t == 'boolean': return 'bit'
    if t == 'character varying': return f"nvarchar({c['len']})" if c['len'] and int(c['len']) <= 4000 else 'nvarchar(max)'
    if t in ('text', 'json', 'jsonb'): return 'nvarchar(max)'
    if t == 'numeric': return f"decimal({c['prec'] or 18},{c['scale'] or 0})"
    if t == 'date': return 'date'
    if t.startswith('timestamp'): return f"datetime2({c['dtp'] or 6})"
    if t == 'double precision': return 'float'
    if t == 'real': return 'real'
    if t == 'uuid': return 'uniqueidentifier'
    raise SystemExit(f'unmapped type {t} on {c}')


def msdefault(c):
    d = c['default']
    if not d or d.startswith('nextval('): return None
    if d in ('now()', 'CURRENT_TIMESTAMP'): return 'SYSDATETIME()'
    if d == 'true': return '1'
    if d == 'false': return '0'
    m = re.fullmatch(r"'(.*)'::[a-z ]+", d)
    if m:
        v = m.group(1).replace("''", "'")
        return v if c['type'] in ('numeric', 'bigint', 'integer', 'smallint') else "N'" + v.replace("'", "''") + "'"
    if re.fullmatch(r'-?\d+(\.\d+)?', d): return d
    raise SystemExit(f'unmapped default {d} on {c}')


def expr(e):
    """PostgreSQL check / index predicate -> T-SQL."""
    e = re.sub(r'::(character varying|text|numeric|bigint|integer|smallint)(\[\])?', '', e)
    e = re.sub(r"'((?:[^']|'')*)'", lambda m: "N'" + m.group(1) + "'", e)
    def arr(m):
        return f"{m.group(1)} IN (" + ', '.join(re.findall(r"N'(?:[^']|'')*'", m.group(2))) + ')'
    e = re.sub(r'(\(?[a-z_]+\)?) = ANY \(\(?ARRAY\[(.*?)\]\)?\)', arr, e)
    return e


lines = ['-- SQL Server baseline: the schema PostgreSQL reaches after the V1..V18 migrations, generated by',
         '-- backend-java/tools/pg_to_mssql.py. Do not edit by hand; regenerate it instead.', '']

# Tables, primary keys, defaults, checks
pks = {}
for t, name, defn in q("select conrelid::regclass::text, conname, pg_get_constraintdef(oid) from pg_constraint where contype='p' and connamespace='public'::regnamespace"):
    pks[t] = (name, re.search(r'\((.*)\)', defn).group(1))
checks = {}
for t, name, defn in q("select conrelid::regclass::text, conname, pg_get_constraintdef(oid) from pg_constraint where contype='c' and connamespace='public'::regnamespace and conrelid <> 0"):
    checks.setdefault(t, []).append((name, expr(defn[len('CHECK '):])))
for t in tables:
    body = []
    for c in cols[t]:
        identity = ' IDENTITY(1,1)' if c['default'].startswith('nextval(') else ''
        d = msdefault(c)
        body.append(f"    {ident(c['name'])} {mstype(c)}{identity}{'' if c['null'] else ' NOT NULL'}" + (f" CONSTRAINT {ident('df_' + t + '_' + c['name'])} DEFAULT {d}" if d else ''))
    if t in pks:
        body.append(f"    CONSTRAINT {ident(pks[t][0])} PRIMARY KEY ({', '.join(ident(x.strip()) for x in pks[t][1].split(','))})")
    for name, e in checks.get(t, []):
        body.append(f"    CONSTRAINT {ident(name)} CHECK {e}")
    lines.append(f"CREATE TABLE {ident(t)} (\n" + ',\n'.join(body) + '\n);')
lines.append('')

# Unique constraints and indexes
nullable = {(t, c['name']) for t in cols for c in cols[t] if c['null']}
for t, name, defn in q("select conrelid::regclass::text, conname, pg_get_constraintdef(oid) from pg_constraint where contype='u' and connamespace='public'::regnamespace"):
    if t in SKIP: continue
    cs = [x.strip() for x in re.search(r'\((.*)\)', defn).group(1).split(',')]
    nul = [c for c in cs if (t, c) in nullable]
    where = (' WHERE ' + ' AND '.join(f'{ident(c)} IS NOT NULL' for c in nul)) if nul else ''
    lines.append(f"CREATE UNIQUE INDEX {ident(name)} ON {ident(t)} ({', '.join(ident(c) for c in cs)}){where};")
constraint_names = {r[0] for r in q("select conname from pg_constraint where connamespace='public'::regnamespace")}
for name, t, defn in q("select indexname, tablename, indexdef from pg_indexes where schemaname='public' order by 1"):
    if name in constraint_names or t in SKIP: continue
    m = re.match(r'CREATE (UNIQUE )?INDEX \S+ ON \S+ USING btree \((.*?)\)( WHERE (.*))?$', defn)
    if not m: raise SystemExit('unmapped index ' + defn)
    cs = [x.strip() for x in m.group(2).split(',')]
    if any(not re.fullmatch(r'[a-z_0-9]+( DESC)?', c) for c in cs): raise SystemExit('expression index ' + defn)
    where = ' WHERE ' + expr(m.group(4)) if m.group(4) else ''
    if m.group(1):
        nul = [c for c in cs if (t, c) in nullable and f'{c} IS NOT NULL' not in (m.group(4) or '')]
        if nul: where = (where + ' AND ' if where else ' WHERE ') + ' AND '.join(f'{ident(c)} IS NOT NULL' for c in nul)
    cols_sql = ', '.join(ident(c.split()[0]) + (' DESC' if c.endswith(' DESC') else '') for c in cs)
    lines.append(f"CREATE {m.group(1) or ''}INDEX {ident(name)} ON {ident(t)} ({cols_sql}){where};")
lines.append('')

# Foreign keys (no action) + delete triggers emulating CASCADE / SET NULL
actions = {}
for child, name, col, parent, pcol, deltype in q("""
        select c.conrelid::regclass::text, c.conname, a.attname, c.confrelid::regclass::text, pa.attname, c.confdeltype
        from pg_constraint c join pg_attribute a on a.attrelid = c.conrelid and a.attnum = c.conkey[1]
        join pg_attribute pa on pa.attrelid = c.confrelid and pa.attnum = c.confkey[1]
        where c.contype = 'f' and c.connamespace='public'::regnamespace and array_length(c.conkey, 1) = 1 order by 1, 2"""):
    lines.append(f"ALTER TABLE {ident(child)} ADD CONSTRAINT {ident(name)} FOREIGN KEY ({ident(col)}) REFERENCES {ident(parent)} ({ident(pcol)});")
    if child in SKIP or parent in SKIP:
        lines.pop()
        continue
    if deltype in ('c', 'n'):
        actions.setdefault(parent, []).append((child, col, pcol, deltype))
lines.append('GO')
for parent, acts in sorted(actions.items()):
    stmts = []
    for child, col, pcol, d in acts:
        if d == 'c':
            stmts.append(f"    DELETE FROM {ident(child)} WHERE {ident(col)} IN (SELECT {ident(pcol)} FROM deleted);")
        else:
            stmts.append(f"    UPDATE {ident(child)} SET {ident(col)} = NULL WHERE {ident(col)} IN (SELECT {ident(pcol)} FROM deleted);")
    pk = pks[parent][1]
    stmts.append(f"    DELETE FROM {ident(parent)} WHERE {ident(pk)} IN (SELECT {ident(pk)} FROM deleted);")
    lines.append(f"CREATE TRIGGER {ident('trg_' + parent + '_delete')} ON {ident(parent)} INSTEAD OF DELETE AS\nBEGIN\n    SET NOCOUNT ON;\n" + '\n'.join(stmts) + '\nEND;\nGO')

# Seed rows (reference data a fresh install needs)
for t in seed_tables:
    cs = [c['name'] for c in cols[t]]
    raw = subprocess.run(['psql', '-h', host, '-U', user, '-d', db, '-At', '-c', f"select coalesce(json_agg(t), '[]') from (select * from {t} order by 1) t"],
                         capture_output=True, text=True, check=True).stdout
    data = json.loads(raw)
    if not data: continue
    ident_col = any(c['default'].startswith('nextval(') for c in cols[t])
    if ident_col: lines.append(f'SET IDENTITY_INSERT {ident(t)} ON;')
    for r in data:
        vals = []
        for c in cols[t]:
            v = r.get(c['name'])
            if v is None: vals.append('NULL')
            elif isinstance(v, bool): vals.append('1' if v else '0')
            elif isinstance(v, (int, float)): vals.append(str(v))
            elif isinstance(v, (list, dict)): vals.append("N'" + json.dumps(v).replace("'", "''") + "'")
            else: vals.append("N'" + str(v).replace('T', ' ', 1).replace("'", "''") + "'" if c['type'].startswith('timestamp') else "N'" + str(v).replace("'", "''") + "'")
        lines.append(f"INSERT INTO {ident(t)} ({', '.join(ident(c) for c in cs)}) VALUES ({', '.join(vals)});")
    if ident_col: lines.append(f'SET IDENTITY_INSERT {ident(t)} OFF;')
open(out, 'w').write('\n'.join(lines) + '\n')
print(f'{len(tables)} tables, {sum(len(a) for a in actions.values())} emulated delete actions on {len(actions)} parent tables -> {out}')
